    ClinicalBreakpointId,
    TestingMethodBefore,
    TestingMethodBeforeDisplay,
    TestingMethodAfter,
    TestingMethodAfterDisplay
FROM @MethodChanges
ORDER BY SentinelEntryId, AntifungalAgent, AstId;