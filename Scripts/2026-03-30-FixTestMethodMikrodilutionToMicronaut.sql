-- Verification query (run before UPDATE)
SELECT
    ast.Id,
    ast.SentinelEntryId,
    ast.TestingMethod,
    CASE ast.TestingMethod
        WHEN 1 THEN 'Mikrodilution'
        WHEN 3 THEN 'Micronaut'
        ELSE CONCAT('Unknown (', ast.TestingMethod, ')')
    END AS TestingMethodDisplay,
    ast.AntifungalAgent,
    ast.MinimumInhibitoryConcentration,
    ast.Resistance,
    ast.ClinicalBreakpointId,
    se.SenderLaboratoryNumber,
    CONCAT('SN-', se.Year, '-', RIGHT(CONCAT('0000', se.YearlySequentialEntryNumber), 4)) AS LaboratoryNumber
FROM AntimicrobialSensitivityTest AS ast
INNER JOIN SentinelEntries AS se ON ast.SentinelEntryId = se.Id
INNER JOIN @TargetSentinelEntries AS tse ON tse.Id = ast.SentinelEntryId
WHERE ast.TestingMethod = 1 -- Mikrodilution
ORDER BY ast.SentinelEntryId, ast.AntifungalAgent, ast.Id;

DECLARE @MethodChanges TABLE
(
    AstId INT NOT NULL,
    SentinelEntryId INT NOT NULL,
    LaboratoryNumber NVARCHAR(20) NOT NULL,
    SenderLaboratoryNumber NVARCHAR(255) NULL,
    AntifungalAgent INT NOT NULL,
    MinimumInhibitoryConcentration DECIMAL(18, 6) NULL,
    Resistance INT NULL,
    ClinicalBreakpointId INT NULL,
    TestingMethodBefore INT NOT NULL,
    TestingMethodBeforeDisplay NVARCHAR(50) NOT NULL,
    TestingMethodAfter INT NOT NULL,
    TestingMethodAfterDisplay NVARCHAR(50) NOT NULL
);

UPDATE ast
SET ast.TestingMethod = 3 -- Micronaut
OUTPUT
    inserted.Id AS AstId,
    inserted.SentinelEntryId,
    CONCAT('SN-', se.Year, '-', RIGHT(CONCAT('0000', se.YearlySequentialEntryNumber), 4)) AS LaboratoryNumber,
    se.SenderLaboratoryNumber,
    inserted.AntifungalAgent,
    inserted.MinimumInhibitoryConcentration,
    inserted.Resistance,
    inserted.ClinicalBreakpointId,
    deleted.TestingMethod AS TestingMethodBefore,
    CASE deleted.TestingMethod
        WHEN 1 THEN 'Mikrodilution'
        WHEN 3 THEN 'Micronaut'
        ELSE CONCAT('Unknown (', deleted.TestingMethod, ')')
    END AS TestingMethodBeforeDisplay,
    inserted.TestingMethod AS TestingMethodAfter,
    CASE inserted.TestingMethod
        WHEN 1 THEN 'Mikrodilution'
        WHEN 3 THEN 'Micronaut'
        ELSE CONCAT('Unknown (', inserted.TestingMethod, ')')
    END AS TestingMethodAfterDisplay
INTO @MethodChanges
FROM AntimicrobialSensitivityTest AS ast
INNER JOIN SentinelEntries AS se ON ast.SentinelEntryId = se.Id
INNER JOIN @TargetSentinelEntries AS tse ON tse.Id = ast.SentinelEntryId
WHERE ast.TestingMethod = 1 -- Mikrodilution
;

-- Export-friendly before/after result (run after UPDATE)
SELECT
    AstId,
